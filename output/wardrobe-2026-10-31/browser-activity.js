async page => {
  const checks=[];
  const assert=(ok,text)=>{if(!ok)throw new Error(text);};
  if(await page.getByRole('button',{name:'标准模式',exact:true}).count())await page.getByRole('button',{name:'标准模式',exact:true}).click();
  const family=await page.evaluate(async()=>{const r=await(await fetch('/api/v1/me')).json();return r.data.households[0].id;});
  const today=new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Shanghai',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date());
  const tomorrow=new Date(Date.parse(today)+86400000).toISOString().slice(0,10);
  const read=async path=>page.evaluate(async path=>(await(await fetch('/api/v1/'+path,{cache:'no-store'})).json()).data,path);
  const before=await read('households/'+family+'/today?date='+tomorrow);
  await page.getByRole('combobox',{name:'带入当天活动',exact:true}).selectOption({label:'09:00 · 公园里走一走'});
  assert(await page.getByLabel('开始时间',{exact:true}).inputValue()==='09:00','plan time missing');
  assert(await page.getByRole('combobox',{name:'活动场景',exact:true}).inputValue()==='outdoor','plan scene missing');
  await page.getByRole('combobox',{name:'活动方式',exact:true}).selectOption('stroller');
  await page.getByText('推车时留意久坐体感，检查裤脚、袜口是否合适。',{exact:true}).waitFor();
  await page.getByRole('combobox',{name:'活动方式',exact:true}).selectOption('active');
  await page.getByText('跑跳时优先便于活动与穿脱的衣物，热了或出汗时及时调整。',{exact:true}).waitFor();
  await page.getByRole('combobox',{name:'活动场景',exact:true}).selectOption('indoor');
  await page.getByText('室外预报仅作准备参考，请按室内实际温度增减，鞋子可按场地选择。',{exact:true}).waitFor();
  checks.push({name:'planned activity time/scene and stroller/active/indoor behavior',passed:true});
  await page.getByLabel('结束时间',{exact:true}).fill('08:00');
  await page.getByRole('alert').filter({hasText:'结束时间须晚于开始时间'}).waitFor();
  await page.getByLabel('结束时间',{exact:true}).fill('10:00');
  await page.getByRole('heading',{name:'从我们已有的衣物里选',exact:true}).waitFor();
  await page.getByRole('button',{name:'刷新天气',exact:true}).click();
  await page.getByRole('status').filter({hasText:'已完成'}).waitFor();
  const after=await read('households/'+family+'/today?date='+tomorrow);
  assert(JSON.stringify(before)===JSON.stringify(after),'weather refresh modified formal day plan');
  checks.push({name:'invalid interval, weather worker refresh and unchanged formal plan',passed:true});
  await page.getByRole('navigation',{name:'主导航'}).getByRole('button',{name:'每日安排',exact:true}).click();
  await page.getByRole('button',{name:'从衣服库搭一套',exact:true}).click();
  await page.getByRole('heading',{name:'今天穿什么',exact:true}).waitFor();
  checks.push({name:'daily weather card opens wardrobe',passed:true});
  const clothes=await read('households/'+family+'/wardrobe');
  const uploaded=clothes.items.find(i=>i.name.startsWith('小熊卫衣（测试'));
  assert(!!uploaded,'uploaded clothes missing before reload');
  await page.reload();
  await page.getByRole('navigation',{name:'主导航'}).getByRole('button',{name:'衣物搭配',exact:true}).click();
  await page.getByRole('button',{name:/^衣服库\s/}).click();
  await page.getByRole('heading',{name:uploaded.name,exact:true}).waitFor();
  const image=page.getByAltText(uploaded.name+'的衣物照片',{exact:true});
  await image.scrollIntoViewIfNeeded(); await image.evaluate(i=>i.decode());
  checks.push({name:'photo and metadata persist after page reload',passed:true});
  return {checks,built:true,syntheticFixtures:true};
}
